"""Only the interval policy consumed by scheduled task publication."""

from pydantic import BaseModel, Field
from app.platform.config.maintenance_defaults import (
    DEFAULT_ACCOUNT_DELETION_INTERVAL_SECONDS,
    DEFAULT_DERIVED_ASSET_CLEANUP_INTERVAL_SECONDS,
    DEFAULT_IMPORT_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_MAIL_OUTBOX_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_NOTIFICATION_CLEANUP_INTERVAL_SECONDS,
    DEFAULT_OBJECT_WRITE_CLEANUP_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_PLAYBACK_OUTBOX_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_REVISION_METADATA_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_REVISION_RENDER_DISPATCH_INTERVAL_SECONDS,
    DEFAULT_SCORE_DELETION_INTERVAL_SECONDS,
    DEFAULT_STORED_OBJECT_RETIREMENT_DISPATCH_INTERVAL_SECONDS,
)


class QueueScheduleConfig(BaseModel):
    ACCOUNT_DELETION_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_ACCOUNT_DELETION_INTERVAL_SECONDS, gt=0
    )
    DERIVED_ASSET_CLEANUP_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_DERIVED_ASSET_CLEANUP_INTERVAL_SECONDS, gt=0
    )
    IMPORT_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_IMPORT_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    MAIL_OUTBOX_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_MAIL_OUTBOX_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    NOTIFICATION_CLEANUP_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_NOTIFICATION_CLEANUP_INTERVAL_SECONDS, gt=0
    )
    OBJECT_WRITE_CLEANUP_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_OBJECT_WRITE_CLEANUP_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    PLAYBACK_OUTBOX_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_PLAYBACK_OUTBOX_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    REALTIME_EVENT_CLEANUP_INTERVAL_SECONDS: int = Field(gt=0)
    REVISION_METADATA_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_REVISION_METADATA_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    REVISION_RENDER_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_REVISION_RENDER_DISPATCH_INTERVAL_SECONDS, gt=0
    )
    SCORE_DELETION_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_SCORE_DELETION_INTERVAL_SECONDS, gt=0
    )
    STORED_OBJECT_RETIREMENT_DISPATCH_INTERVAL_SECONDS: int = Field(
        default=DEFAULT_STORED_OBJECT_RETIREMENT_DISPATCH_INTERVAL_SECONDS, gt=0
    )
