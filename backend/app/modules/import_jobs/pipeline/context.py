"""Pipeline import-job context and shared runtime state."""

import os
import time
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, List, Optional
from app.task_queue.protocols import CeleryTaskLike

from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.logger import logger
from app.core.settings.task_reliability import get_task_reliability_settings
from app.modules.import_jobs.dispatch_service import (
    ImportExecutionLease,
    StaleImportDispatchAttempt,
)
from app.processing.engines.omr import OmrSuccessResult
from app.modules.import_jobs.execution_recorder import import_execution_recorder
from app.modules.import_jobs.pipeline.artifact_recorder import replace_files
from app.modules.import_jobs.pipeline.step_tracker import StepTracker
from app.db.models.import_job import ImportArtifactKind

if TYPE_CHECKING:
    from app.modules.import_jobs.pipeline.base import Pipeline


@dataclass
class JobContext:
    """Mutable import-job state shared across pipeline steps."""

    lease: ImportExecutionLease
    db: Session
    celery_task: CeleryTaskLike
    image_paths: List[str]

    raw_paths: List[str] = field(default_factory=list)
    omr_result: Optional[OmrSuccessResult] = None
    main_xml: Optional[str] = None

    job_temp: str = ""
    raw_dir: str = ""
    omr_dir: str = ""

    _start_ts: float = field(default_factory=time.time)
    _deadline: float = 0
    _tracker: StepTracker | None = None
    _order_map: dict[str, int] = field(default_factory=dict)

    @property
    def job_id(self) -> str:
        return self.lease.job_uuid

    def __post_init__(self):
        """Initialize derived paths and timeout state."""
        max_time = int(get_task_reliability_settings().MAX_PROCESSING_TIME)
        self._deadline = self._start_ts + max_time

        self.job_temp = os.path.join(settings.WORK_ROOT, self.job_id, self.lease.token)
        self.raw_dir = os.path.join(self.job_temp, "raw")
        self.omr_dir = os.path.join(self.job_temp, "omr")

        self._tracker = None

    def set_order_map(self, pipeline: "Pipeline") -> None:
        """Bind the runtime step order generated by the pipeline."""
        self._order_map = pipeline.build_order_map()
        self._tracker = StepTracker(self.job_id, self._upsert, self._order_map)

    def _upsert(self, name: str, **kwargs) -> None:
        """Persist step-tracking state."""
        try:
            import_execution_recorder.upsert_step(self.db, self.lease, name=name, **kwargs)
        except StaleImportDispatchAttempt:
            raise
        except Exception as exc:
            logger.bind(
                event="import_pipeline.step_state_upsert_failed",
                job_id=self.job_id,
                step=name,
                exception_type=type(exc).__name__,
            ).opt(exception=exc).error("Import pipeline step state upsert failed")
            self._recover_session()

    def remaining(self) -> int:
        """Return remaining task time in seconds."""
        return max(0, int(self._deadline - time.time()))

    def progress(
        self,
        msg: str,
        prog: int,
        *,
        current_step: str | None = None,
    ) -> None:
        """Persist and log task progress updates."""
        try:
            import_execution_recorder.record_progress(
                self.db,
                self.lease,
                prog,
                current_step=current_step,
            )
        except StaleImportDispatchAttempt:
            raise
        except Exception as exc:
            logger.bind(
                event="import_pipeline.progress_update_failed",
                job_id=self.job_id,
                progress=prog,
                current_step=current_step,
                exception_type=type(exc).__name__,
            ).opt(exception=exc).error("Import pipeline progress update failed")
            self._recover_session()

        try:
            step = current_step
            if step and self._tracker:
                self._tracker.on_progress(step)
        except StaleImportDispatchAttempt:
            raise
        except Exception as exc:
            logger.bind(
                event="import_pipeline.tracker_progress_failed",
                job_id=self.job_id,
                current_step=current_step,
                exception_type=type(exc).__name__,
            ).opt(exception=exc).warning("Import pipeline tracker progress update failed")

        logger.bind(
            event="import_pipeline.progress_updated",
            job_id=self.job_id,
            status=msg,
            progress=prog,
            current_step=current_step,
        ).info("Import pipeline progress updated")

    def _recover_session(self) -> None:
        """Recover a worker session interrupted during a progress update."""
        try:
            self.db.rollback()
        except Exception:
            self.db.invalidate()

    def complete(self) -> None:
        """Finalize successful task execution."""
        try:
            if self._tracker:
                self._tracker.complete_last(final_step_name="ocr_completed")
        except StaleImportDispatchAttempt:
            raise
        except Exception as exc:
            logger.bind(
                event="import_pipeline.tracker_complete_failed",
                job_id=self.job_id,
                exception_type=type(exc).__name__,
            ).opt(exception=exc).debug("Import pipeline tracker completion failed")

        if not self.main_xml or not os.path.exists(self.main_xml):
            raise FileNotFoundError("Canonical MusicXML was not produced")
        replace_files(self.lease, ImportArtifactKind.REVIEW_MUSICXML, [self.main_xml])
        total_time = int(time.time() - self._start_ts)
        import_execution_recorder.finalize_success(
            self.db, self.lease, total_time_seconds=total_time
        )
        logger.bind(
            event="import_pipeline.job_completed",
            job_id=self.job_id,
            duration_seconds=total_time,
        ).info("Import pipeline job completed")

    def update_celery_state(self, status: str, progress: int, current_step: str) -> None:
        """Update the Celery task state payload."""
        self.celery_task.update_state(
            state="RUNNING",
            meta={
                "status": status,
                "progress": progress,
                "current_step": current_step,
            },
        )

    def create_dirs(self) -> None:
        """Create per-job working directories."""
        dirs = [self.raw_dir, self.omr_dir]
        for directory in dirs:
            os.makedirs(directory, exist_ok=True)

    @property
    def is_multi_image(self) -> bool:
        """Return whether the task runs in multi-image mode."""
        return len(self.image_paths) > 1

    @property
    def first_image(self) -> Optional[str]:
        """Return the first copied image path, if any."""
        return self.raw_paths[0] if self.raw_paths else None
