import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const sourceRoot = path.join(root, 'src');
const reportPath = path.resolve(
  root,
  '..',
  '..',
  'docs',
  'engineering',
  'reviews',
  '2026-08-12-customer-web-editor-legacy-inventory.md',
);

const legacyPatterns = [
  {
    id: 'score-entity-model',
    title: 'Legacy ScoreEntity model',
    regexp: /\bScoreEntity\b/g,
    rationale: 'Old editor entity union used by parser, Inspector, selection, and mutation flows.',
  },
  {
    id: 'blank-type',
    title: 'Legacy Blank type',
    regexp: /\bBlank\b/g,
    rationale: 'Old domain representation for MusicXML <forward>; target model uses timeline gaps instead.',
  },
  {
    id: 'blank-entity',
    title: 'Legacy blank entity discriminator',
    regexp: /\bblank\b/g,
    rationale: 'Old runtime discriminator and comments around blank/forward behavior.',
  },
  {
    id: 'verovio-space-hit',
    title: 'Verovio space handling',
    regexp: /data-class=["']space["']/g,
    rationale: 'Verovio render-space handling must stay adapter-only and must not reintroduce ordinary editable blank event hits.',
  },
];

const ignoredDirectories = new Set([
  '.next',
  'coverage',
  'node_modules',
  'test-results',
]);

const checkOnly = process.argv.includes('--check');

function main() {
  const matches = scanSource();
  const report = renderReport(matches);

  if (checkOnly) {
    if (!existsSync(reportPath)) {
      throw new Error(`Legacy editor inventory report is missing: ${toDisplayPath(reportPath)}`);
    }

    const current = readFileSync(reportPath, 'utf8');
    if (current !== report) {
      throw new Error(
        [
          'Legacy editor inventory report is stale.',
          `Run: npm run inventory:editor-legacy`,
          `Report: ${toDisplayPath(reportPath)}`,
        ].join('\n'),
      );
    }
    console.log(`Legacy editor inventory is current: ${toDisplayPath(reportPath)}`);
    return;
  }

  writeFileSync(reportPath, report, 'utf8');
  console.log(`Wrote legacy editor inventory: ${toDisplayPath(reportPath)}`);
}

function scanSource() {
  const files = collectFiles(sourceRoot)
    .filter((file) => /\.(ts|tsx|js|jsx|mjs|cjs)$/.test(file))
    .sort((left, right) => toDisplayPath(left).localeCompare(toDisplayPath(right)));

  return legacyPatterns.map((pattern) => {
    const hits = [];
    for (const file of files) {
      const content = readFileSync(file, 'utf8');
      const lines = content.split(/\r?\n/);
      lines.forEach((line, index) => {
        pattern.regexp.lastIndex = 0;
        if (!pattern.regexp.test(line)) {
          return;
        }
        hits.push({
          file: toDisplayPath(file),
          line: index + 1,
          snippet: line.trim(),
        });
      });
    }
    return {
      ...pattern,
      hits,
    };
  });
}

function collectFiles(directory) {
  const result = [];
  for (const entry of readdirSync(directory)) {
    if (ignoredDirectories.has(entry)) {
      continue;
    }
    const absolute = path.join(directory, entry);
    const stat = statSync(absolute);
    if (stat.isDirectory()) {
      result.push(...collectFiles(absolute));
    } else if (stat.isFile()) {
      result.push(absolute);
    }
  }
  return result;
}

function renderReport(matches) {
  const totalHits = matches.reduce((sum, pattern) => sum + pattern.hits.length, 0);
  const files = new Set(matches.flatMap((pattern) => pattern.hits.map((hit) => hit.file)));
  const lines = [
    '# Customer Web editor legacy dependency inventory',
    '',
    'Generated by `npm run inventory:editor-legacy` from `apps/customer-web`.',
    '',
    'This inventory records the remaining Customer Web editor code that still references the legacy `ScoreEntity` / `Blank` / Verovio space-hit model while REC-007 migrates the editor toward the new `editor-domain` model.',
    '',
    'Do not treat this document as approval to keep the legacy model long-term. It is an executable migration ledger: update it when a replacement step intentionally removes or moves a legacy dependency.',
    '',
    '## Summary',
    '',
    `- Total matching lines: ${totalHits}`,
    `- Files with matches: ${files.size}`,
    '',
    '| Pattern | Matching lines | Meaning |',
    '| --- | ---: | --- |',
    ...matches.map((pattern) => (
      `| ${pattern.title} | ${pattern.hits.length} | ${pattern.rationale} |`
    )),
    '',
    '## Matches by pattern',
    '',
  ];

  for (const pattern of matches) {
    lines.push(`### ${pattern.title}`, '');
    lines.push(pattern.rationale, '');
    if (pattern.hits.length === 0) {
      lines.push('No matches.', '');
      continue;
    }

    const byFile = groupByFile(pattern.hits);
    for (const [file, hits] of byFile) {
      lines.push(`#### \`${file}\``, '');
      for (const hit of hits) {
        lines.push(`- L${hit.line}: \`${escapeInlineCode(hit.snippet)}\``);
      }
      lines.push('');
    }
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

function groupByFile(hits) {
  const grouped = new Map();
  for (const hit of hits) {
    const entries = grouped.get(hit.file) ?? [];
    entries.push(hit);
    grouped.set(hit.file, entries);
  }
  return grouped;
}

function toDisplayPath(file) {
  return path.relative(path.resolve(root, '..', '..'), file).replaceAll(path.sep, '/');
}

function escapeInlineCode(value) {
  return value.replaceAll('`', '\\`');
}

main();
