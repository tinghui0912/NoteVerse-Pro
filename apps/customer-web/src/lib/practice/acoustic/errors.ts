export type AcousticAnalysisErrorCode =
  (typeof ACOUSTIC_ANALYSIS_ERROR_CODES)[number];
export function isAcousticAnalysisErrorCode(
  value: unknown,
): value is AcousticAnalysisErrorCode {
  return (
    typeof value === 'string' &&
    ACOUSTIC_ANALYSIS_ERROR_CODES.some((code) => code === value)
  );
}
export class AcousticAnalysisError extends Error {
  constructor(
    readonly code: AcousticAnalysisErrorCode,
    options?: ErrorOptions,
  ) {
    super(code, options);
    this.name = 'AcousticAnalysisError';
  }
}
export function fail(code: AcousticAnalysisErrorCode): never {
  throw new AcousticAnalysisError(code);
}
